// Session 2: validate completeness, ordering, source links and public UI wiring of Z-A story.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {ZA_MAIN_HANDBOOK} from '../src/guides/za-main-handbook.js';
import {ZA_MAIN} from '../src/guides/za-main-data.js';
import {ZA_MEGA} from '../src/guides/za-items-data.js';
import {ZA_MAIN_STEPS} from '../src/guides/za-walkthrough-details.js';
const cards=Object.entries(ZA_MAIN_HANDBOOK);
assert.equal(cards.length,42,'all 42 base-game main missions have handbook entries');
assert.deepEqual(cards.map(([id])=>+id),Array.from({length:42},(_,i)=>i+1));
assert.equal(ZA_MAIN.length,42);
let total=0;
for(const mission of ZA_MAIN){
 const h=ZA_MAIN_HANDBOOK[mission.id];
 assert.ok(h?.startHint?.length>=20,'start landmark missing for '+mission.id);
 assert.ok(h?.unlock?.length>=15,'unlock missing for '+mission.id);
 assert.ok(Array.isArray(h.steps)&&h.steps.length>=4,'too few objective steps for '+mission.id);
 assert.ok(h.steps.every(x=>typeof x.ru==='string'&&x.ru.length>=45),'short/nonexistent step '+mission.id);
 assert.equal(new Set(h.steps.map(x=>x.id)).size,h.steps.length,'step ids repeat for '+mission.id);
 assert.ok(h.steps.every(x=>/^s\d{2}$/.test(x.id)),'unstable step identifiers '+mission.id);
 assert.ok(h.sources?.length>0&&h.sources.every(x=>x.startsWith('https://')),'must cite sources '+mission.id);
 assert.equal(h.status,'source-checked','review provenance missing for '+mission.id);
 total+=h.steps.length;
}
assert.ok(total>=240,'mission objectives insufficiently expanded');
const content=id=>ZA_MAIN_HANDBOOK[id].steps.map(x=>x.ru).join(' ');
assert.match(content(5),/№1/);
assert.match(content(5),/№2/);
assert.match(content(5),/№3/);
assert.match(content(9),/Absolite/);
assert.match(content(14),/DYN4MO/);
assert.match(content(14),/✓/);
assert.match(content(19),/Ice Beam/);
assert.match(content(19),/Klefki/);
assert.match(content(19),/иллюзорн/);
assert.match(content(20),/Syndicate/);
assert.match(content(30),/Zygarde/);
assert.match(content(35),/Elevator Key/);
assert.match(content(35),/B3F/);
assert.match(content(37),/Corbeau/);
assert.match(content(37),/лес/);
assert.match(content(38),/Centrico Plaza/);
assert.match(content(39),/15 Reward Matches/);
assert.match(content(42),/№40/);
assert.match(content(42),/№41/);
assert.doesNotMatch(content(42),/требуется 15 Reward Matches/);
assert.doesNotMatch(content(29),/Thick Fat/,'Legends: Z-A ability descriptions are not battle abilities');
assert.match(ZA_MAIN_STEPS[9],/Absolite/);
const absolite=ZA_MEGA.find(x=>x.name==='Absolite');
assert.ok(absolite);
assert.match(absolite.location,/№9/,'Absolite is obtained in mission 9');
assert.doesNotMatch(ZA_MAIN[8].location,/Jaune Sector 6/,'old rogue Absol location must not show');
const guide=readFileSync(new URL('../src/guides/guides-v09.js',import.meta.url),'utf8');
assert.match(guide,/import \{ZA_MAIN_HANDBOOK\}/,'new handbook must be imported');
assert.match(guide,/ZA_MAIN_HANDBOOK\[x\.id\]/,'all main rows must use rich records');
assert.match(guide,/hasLegacyStepMarks/,'old progress must not silently map to different instructions');
assert.match(guide,/stepKey\(x,i\)/,'stable checklist keys required');
assert.match(guide,/x\.sources\?\.length/,'reference URLs must be visible');
const sideHint=guide.slice(guide.indexOf('function objectiveSteps('),guide.indexOf('function stepMarkup('));
assert.match(sideHint,/if\(x\.kind==='side'/,'side quest handling remains supported');
assert.doesNotMatch(sideHint,/x\.kind==='dlc-side'/,'DLC portals cannot be given blue side marker directions');
console.log('Session 2: '+cards.length+' story missions, '+total+' objective steps, sourced records and UI integrations checked.');
